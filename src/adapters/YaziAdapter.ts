export class YaziAdapter {
    public async apply(spore: Spore, config: YaziAdapterConfig): Promise<Report> {
        const startedAt = new Date().toISOString();

        const missing = REQUIRED_TOKENS.filter(k => spore.colors[k] === undefined);
        if (missing.length > 0) {
            throw new Error(`Recipe "${spore.recipe}" is missing yazi tokens: ${missing.join(', ')}`);
        }

        const theme = renderTheme(spore.colors as Record<string, string>);

        await mkdir(dirname(config.outputPath), { recursive: true });
        await writeFile(config.outputPath, theme, 'utf8');

        return {
            target:     spore.target,
            profile:    spore.profile,
            recipe:     spore.recipe,
            status:     'ok',
            inputs:     { basePalette: spore.recipe },
            outputs:    [config.outputPath],
            warnings:   [],
            errors:     [],
            startedAt,
            finishedAt: new Date().toISOString(),
        };
    }
}
