// Regenerates the targets table in README.md from the repo itself: target
// folders, plant hook destinations, and which profiles use each target.
// Only the one-line notes are hand-written, in docs/target-notes.json.
//
//   deno task readme:targets           rewrite the table
//   deno task readme:targets --check   exit 1 if the table is out of date

const repo = new URL("../../..", import.meta.url).pathname;
const START = "<!-- targets:start -->";
const END = "<!-- targets:end -->";

interface HookStep {
  type?: string;
  dest?: string[];
}

async function readJson<T>(path: string): Promise<T | undefined> {
  try {
    return JSON.parse(await Deno.readTextFile(path)) as T;
  } catch {
    return undefined;
  }
}

async function names(dir: string, filter: (entry: Deno.DirEntry) => boolean): Promise<string[]> {
  const found: string[] = [];
  for await (const entry of Deno.readDir(dir)) if (filter(entry)) found.push(entry.name);
  return found.sort();
}

const notes = (await readJson<Record<string, string>>(`${repo}docs/target-notes.json`)) ?? {};
const targets = await names(`${repo}targets`, (entry) => entry.isDirectory);

// Plain profiles list their targets; compositions reuse those profiles.
const usage = new Map<string, number>();
for (const file of await names(`${repo}profiles`, (entry) => entry.name.endsWith(".json"))) {
  const profile = await readJson<{ targets?: Record<string, string> }>(`${repo}profiles/${file}`);
  for (const target of Object.keys(profile?.targets ?? {})) usage.set(target, (usage.get(target) ?? 0) + 1);
}

const cell = (text: string) => text.replaceAll("|", "\\|");
const rows: string[] = [];
const retired: string[] = [];
const missingNotes: string[] = [];

for (const target of targets) {
  const note = notes[target];
  if (!note) missingNotes.push(target);
  if (!usage.get(target)) {
    retired.push(`\`${target}\``);
    continue;
  }

  const hook = await readJson<{ steps?: HookStep[] }>(`${repo}targets/${target}/hooks/plant.json`);
  const dests = (hook?.steps ?? []).filter((step) => step.type === "copy").flatMap((step) => step.dest ?? []);
  const lands = dests.length > 0
    ? `\`${dests[0]}\`${dests.length > 1 ? ` +${dests.length - 1}` : ""}`
    : hook?.steps?.length ? "via its hook script" : "—";

  rows.push(`| \`${target}\` | ${cell(note ?? "—")} | ${lands} | ${usage.get(target)} |`);
}

const table = [
  START,
  "<!-- Generated by `deno task readme:targets`; edit docs/target-notes.json instead. -->",
  "",
  "| Target | What it themes | Lands in | Profiles |",
  "|---|---|---|---|",
  ...rows,
  "",
  `Retired (in \`targets/\`, used by no profile): ${retired.join(", ") || "none"}.`,
  END,
].join("\n");

const readmePath = `${repo}README.md`;
const readme = await Deno.readTextFile(readmePath);
const start = readme.indexOf(START);
const end = readme.indexOf(END);
if (start === -1 || end === -1) {
  console.error(`README.md has no ${START} … ${END} block.`);
  Deno.exit(1);
}

const updated = readme.slice(0, start) + table + readme.slice(end + END.length);
if (missingNotes.length > 0) {
  console.warn(`No note in docs/target-notes.json for: ${missingNotes.join(", ")}`);
}

if (Deno.args.includes("--check")) {
  if (updated !== readme) {
    console.error("The targets table in README.md is out of date. Run: deno task readme:targets");
    Deno.exit(1);
  }
  console.log("Targets table is up to date.");
} else {
  await Deno.writeTextFile(readmePath, updated);
  console.log(`Targets table: ${rows.length} in use, ${retired.length} retired.`);
}
